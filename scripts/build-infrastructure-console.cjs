'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { loadProfile, readiness, cloudflareBindings } = require('../packages/infrastructure-adapters/index.cjs');
const ROOT = path.resolve(__dirname, '..');
const source = path.join(ROOT, 'infrastructure/app');
const destination = path.join(ROOT, 'dist/infrastructure');
const local = loadProfile(path.join(ROOT, 'infra/profiles/local.json'));
const cloudflare = loadProfile(path.join(ROOT, 'infra/profiles/cloudflare-production.json'));
const generatedAt = '2026-09-30T21:00:00Z';
const localReadiness = readiness(local, { VAULT_KEY: 'injected-at-runtime', AUDIT_KEY: 'injected-at-runtime' }, generatedAt);
const cloudflareReadiness = readiness(cloudflare, {}, generatedAt);
fs.rmSync(destination, { recursive: true, force: true });
fs.mkdirSync(destination, { recursive: true });
for (const name of ['index.html', 'styles.css', 'app.js']) fs.copyFileSync(path.join(source, name), path.join(destination, name));
fs.writeFileSync(path.join(destination, 'readiness.local.json'), JSON.stringify(localReadiness, null, 2) + '\n');
fs.writeFileSync(path.join(destination, 'readiness.cloudflare.json'), JSON.stringify(cloudflareReadiness, null, 2) + '\n');
fs.writeFileSync(path.join(destination, 'binding-plan.json'), JSON.stringify(cloudflareBindings(cloudflare), null, 2) + '\n');
fs.writeFileSync(path.join(destination, 'infrastructure-manifest.json'), JSON.stringify({ version: '0.10.0', synthetic: true, adapters: 6, local_status: localReadiness.status, cloud_status: cloudflareReadiness.status, production_ready: false, publication: 'blocked' }, null, 2) + '\n');
console.log('Consola de infraestructura generada: local ejecutable, producción bloqueada.');
